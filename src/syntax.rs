//! Syntax themes two-face doesn't embed, built in code from an editor theme's token colours.

use std::str::FromStr;

use two_face::re_exports::syntect::highlighting::{
    Color, FontStyle, ScopeSelectors, StyleModifier, Theme, ThemeItem, ThemeSettings,
};

/// A rule colours every scope selector in its list; alpha is already blended over `bg`.
type Rule = (&'static [&'static str], u32, FontStyle);

#[derive(Debug)]
pub struct Custom {
    pub name: &'static str,
    pub fg: u32,
    pub bg: u32,
    pub caret: u32,
    pub selection: u32,
    pub rules: &'static [Rule],
}

fn color(hex: u32) -> Color {
    Color {
        r: (hex >> 16) as u8,
        g: (hex >> 8) as u8,
        b: hex as u8,
        a: 0xff,
    }
}

impl Custom {
    pub fn build(&self) -> Theme {
        Theme {
            name: Some(self.name.into()),
            author: None,
            settings: ThemeSettings {
                foreground: Some(color(self.fg)),
                background: Some(color(self.bg)),
                caret: Some(color(self.caret)),
                selection: Some(color(self.selection)),
                ..ThemeSettings::default()
            },
            scopes: self
                .rules
                .iter()
                .filter_map(|&(scopes, fg, font_style)| {
                    Some(ThemeItem {
                        scope: ScopeSelectors::from_str(&scopes.join(", ")).ok()?,
                        style: StyleModifier {
                            foreground: Some(color(fg)),
                            background: None,
                            font_style: Some(font_style),
                        },
                    })
                })
                .collect(),
        }
    }
}

