#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_beardy_blueberry_rule_parses() {
        let theme = BEARDY_BLUEBERRY.build();
        assert_eq!(theme.scopes.len(), BEARDY_BLUEBERRY.rules.len());
    }

    #[test]
    fn beardy_blueberry_colours_rust_like_the_editor_theme() {
        use two_face::re_exports::syntect::easy::HighlightLines;

        let ss = two_face::syntax::extra_newlines();
        let theme = BEARDY_BLUEBERRY.build();
        let mut h = HighlightLines::new(ss.find_syntax_by_extension("rs").unwrap(), &theme);
        let ranges = h.highlight_line("fn main() { \"hi\" }\n", &ss).unwrap();
        let fg = |text: &str| {
            let (st, _) = ranges.iter().find(|(_, s)| *s == text).unwrap();
            (st.foreground.r, st.foreground.g, st.foreground.b)
        };
        assert_eq!(fg("main"), (0x69, 0xc3, 0xff));
        assert_eq!(fg("hi"), (0x3c, 0xec, 0x85));
    }
}
